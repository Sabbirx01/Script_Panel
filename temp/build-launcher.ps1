<#
    build-launcher.ps1  -  pack the WHOLE panel into ONE encrypted setup exe
    ===========================================================================
    Customer-ke ekta file-i dite hoy:  DeveloperXPanel-Setup.exe

    bhitore ki thake (sob, AES-256 kore bandha):
        DeveloperXBulkAccPanel.exe
        tools\            (4 ta tool, .env / accounts.txt baad)
        runtime\          python + chromium
        .playwright\      panel-er nijer driver
        portable.txt      data\ exe-er pash-e thakbe

    Payload format (build-er somoy thik hoy):
        "DXPL"  4 B   magic
        format  1 B   = 1
        IV     16 B   random, per build
        SHA-256 32 B  plaintext-er hash  <- integrity
        cipher  ..    AES-256-CBC + PKCS7

    Sotti kotha (mithye boli na):
      AES key ta exe-r bhitorei thakte hoy, karon customer-er PC-te payload
      khuLte hoy. Tai eta RODH, abhedyo noy - "exe khuLe 549 MB payload ber
      kore choriye dao" ta bondho kore. Integrity check ta asol kaaj: noshta
      ba splice kora setup half-install na kore poriskar fail kore.
      Licence-er asol surakkha server-side RSA - eta tar bodol noy.

    Usage:
        powershell -File ..\temp\build-launcher.ps1 -Version 1.1.1
        powershell -File ..\temp\build-launcher.ps1 -Version 1.1.1 -SkipBundle
        powershell -File ..\temp\build-launcher.ps1 -KeyOnly      # compile check er age

    Note: payload ~1060 MB, tai ei build 5-15 minute ney.
#>

[CmdletBinding()]
param(
    [string]$Version = "",
    [string]$Bundle  = "",
    [switch]$SkipBundle,
    [switch]$KeepPayload,
    [switch]$KeyOnly
)

$ErrorActionPreference = 'Stop'

$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$root      = Split-Path -Parent $scriptDir
$keyFile   = Join-Path $root 'launcher\payload.key'
$keyCs     = Join-Path $root 'launcher\PayloadKey.g.cs'
$payloadDir = Join-Path $root 'launcher\payload'

function Head($t) { Write-Host ""; Write-Host "  $t" -ForegroundColor White }
function Ok($t)   { Write-Host "  $t" -ForegroundColor Green }
function Warn2($t){ Write-Host "  $t" -ForegroundColor Yellow }
function Bad($t)  { Write-Host "  $t" -ForegroundColor Red }

# ------------------------------------------------------------------- key + C#
function New-KeyBytes {
    $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
    try { $b = New-Object byte[] 32; $rng.GetBytes($b); return $b } finally { $rng.Dispose() }
}

function New-MaskBytes {
    $rng = [Security.Cryptography.RandomNumberGenerator]::Create()
    try { $b = New-Object byte[] 16; $rng.GetBytes($b); return $b } finally { $rng.Dispose() }
}

function ByteLiteral([byte[]]$bytes) {
    return (($bytes | ForEach-Object { '0x' + $_.ToString('X2') }) -join ', ')
}

function Write-KeySource([byte[]]$key) {
    $mask = New-MaskBytes
    $enc  = New-Object byte[] $key.Length
    for ($i = 0; $i -lt $key.Length; $i++) { $enc[$i] = $key[$i] -bxor $mask[$i % $mask.Length] }

    $text = @"
// ---------------------------------------------------------------------------
//  GENERATED by temp\build-launcher.ps1 - do not edit, do not commit.
//
//  Holds the AES key that unlocks the packed panel. It is split into two
//  arrays and XOR-folded so the key is not a recognisable 32-byte blob in a
//  decompiler dump. That is deterrence, not secrecy: the key must be readable
//  by this process at run time, so a determined attacker can recover it.
// ---------------------------------------------------------------------------
namespace LaunchPanel;

internal static class PayloadKey
{
    private static readonly byte[] Parts = { $(ByteLiteral $enc) };

    private static readonly byte[] Mask = { $(ByteLiteral $mask) };

    public static byte[] Get()
    {
        var key = new byte[Parts.Length];
        for (int i = 0; i < key.Length; i++)
        {
            key[i] = (byte)(Parts[i] ^ Mask[i % Mask.Length]);
        }
        return key;
    }
}
"@

    [IO.File]::WriteAllText($keyCs, $text, (New-Object Text.UTF8Encoding($false)))
    Ok ("PayloadKey.g.cs written  (" + $key.Length + "-byte key, XOR-masked)")
}

function Get-OrCreateKey {
    if (-not (Test-Path -LiteralPath $payloadDir)) { New-Item -ItemType Directory -Force -Path $payloadDir | Out-Null }

    if (Test-Path -LiteralPath $keyFile) {
        $key = [Convert]::FromBase64String((Get-Content -LiteralPath $keyFile -Raw).Trim())
        if ($key.Length -ne 32) { Bad "payload.key is not 32 bytes - delete it to rotate."; exit 1 }
        Ok "reusing launcher\payload.key"
    } else {
        $key = New-KeyBytes
        Set-Content -LiteralPath $keyFile -Value ([Convert]::ToBase64String($key)) -Encoding ASCII
        Ok "generated launcher\payload.key (new key)"
    }
    return ,$key
}

Write-Host ""
Write-Host "  DEVELOPER X  -  ONE-FILE ENCRYPTED SETUP" -ForegroundColor Cyan
Write-Host "  ---------------------------------------" -ForegroundColor DarkCyan

$key = Get-OrCreateKey
Write-KeySource $key

if ($KeyOnly) {
    Write-Host ""
    Ok 'Key material ready (compile check mode - nothing else was built)'
    Write-Host ""
    exit 0
}

# ------------------------------------------------------------------- 1. version
if ([string]::IsNullOrWhiteSpace($Version)) {
    $m = [regex]::Match((Get-Content -LiteralPath (Join-Path $root 'source\AISuitePanel.csproj') -Raw -Encoding UTF8),
                        '<Version>\s*([0-9]+(\.[0-9]+){1,3})\s*</Version>')
    if ($m.Success) { $Version = $m.Groups[1].Value }
}
if ($Version -notmatch '^\d+(\.\d+){1,3}$') { Bad "Version must look like 1.1.1 (got '$Version')"; exit 1 }
$tag = "v$Version"

if ([string]::IsNullOrWhiteSpace($Bundle)) { $Bundle = Join-Path $root 'dist\DeveloperX-Portable' }

Head 'Plan'
Write-Host "  version : $Version"
Write-Host "  bundle  : $Bundle"

# -------------------------------------------------------------------- 2. bundle
if (-not $SkipBundle) {
    Head 'Building the portable bundle (this prunes browsers and secrets)'
    & powershell -NoProfile -ExecutionPolicy Bypass -File (Join-Path $scriptDir 'build-portable.ps1') -Clean
    if ($LASTEXITCODE -ne 0) { Bad "build-portable.ps1 failed (exit $LASTEXITCODE)"; exit 1 }
} else {
    Head 'Reusing the existing bundle'
}

$mainExe = Join-Path $root 'output\DeveloperXBulkAccPanel.exe'
$panelExe = Join-Path $Bundle 'DeveloperXBulkAccPanel.exe'
if (-not (Test-Path -LiteralPath $mainExe)) { Bad "MAIN working exe is missing: $mainExe"; exit 1 }
if (-not (Test-Path -LiteralPath $panelExe)) { Bad "Panel exe not in the bundle: $panelExe"; exit 1 }

# Hard identity gate: the encrypted customer payload must contain the exact
# working EXE selected by the operator, not an older build from another folder.
$mainHash = (Get-FileHash -LiteralPath $mainExe -Algorithm SHA256).Hash.ToUpperInvariant()
$bundleHash = (Get-FileHash -LiteralPath $panelExe -Algorithm SHA256).Hash.ToUpperInvariant()
Write-Host "  MAIN output hash  : $mainHash"
Write-Host "  BUNDLE panel hash : $bundleHash"
if ($mainHash -ne $bundleHash) {
    Bad "REFUSING TO PACK: bundle panel EXE is not byte-identical to output\\DeveloperXBulkAccPanel.exe"; exit 1
}
Ok 'identity gate passed: encrypted payload uses the exact main output EXE'

if (-not (Test-Path -LiteralPath (Join-Path $Bundle '.playwright'))) {
    Bad "bundle\\.playwright is missing - the panel cannot start without it."; exit 1
}

# ------------------------------------------------------------------ 3. leak scan
Head 'Checking the bundle carries no secrets'

$leakPatterns = @('^\.env$', '^accounts?\.txt$', '^cookies?\.txt$', '^claims\.txt$', '^dead_accounts\.txt$')
$leaks = @()
Get-ChildItem -LiteralPath $Bundle -Recurse -File -Force -ErrorAction SilentlyContinue | ForEach-Object {
    foreach ($p in $leakPatterns) {
        if ($_.Name -match $p) { $leaks += $_.FullName.Substring($Bundle.Length).TrimStart('\'); break }
    }
}
if ($leaks.Count -gt 0) {
    Bad "Secret-looking files found in the bundle - refusing to pack them into a customer exe:"
    $leaks | Select-Object -First 20 | ForEach-Object { Write-Host "    $_" -ForegroundColor Red }
    exit 1
}
Ok 'no .env / accounts.txt / cookies.txt in the bundle'

foreach ($forbidden in @('source', 'licence-local', '_archive', '_backups', 'connector')) {
    if (Test-Path -LiteralPath (Join-Path $Bundle $forbidden)) {
        Warn2 "bundle contains $forbidden\ - check this is intended"
    }
}

$bundleMb = [math]::Round(((Get-ChildItem -LiteralPath $Bundle -Recurse -File -Force -ErrorAction SilentlyContinue |
                Measure-Object -Property Length -Sum).Sum / 1MB), 1)
Write-Host "  bundle size : $bundleMb MB"

# --------------------------------------------------------- 4. zip it (plaintext)
Head 'Packing the bundle'

$plainZip = Join-Path $payloadDir 'payload.zip'
$encFile  = Join-Path $payloadDir 'payload.enc'
foreach ($f in @($plainZip, $encFile)) { if (Test-Path -LiteralPath $f) { Remove-Item -LiteralPath $f -Force } }

Add-Type -AssemblyName System.IO.Compression.FileSystem
[IO.Compression.ZipFile]::CreateFromDirectory(
    $Bundle, $plainZip, [IO.Compression.CompressionLevel]::Optimal, $false)

# the version marker travels as its own tiny resource, so a launch that is
# already up to date never has to decrypt the big payload
Set-Content -LiteralPath (Join-Path $payloadDir 'bundle-version.txt') -Value $Version -Encoding UTF8

$zipMb = [math]::Round((Get-Item -LiteralPath $plainZip).Length / 1MB, 1)
Ok "payload.zip = $zipMb MB  (from $bundleMb MB)"

# ------------------------------------------------------------ 5. encrypt it
Head 'Encrypting the payload (AES-256-CBC)'

$sha = [Security.Cryptography.SHA256]::Create()
$plainHash = $null
$fsr = [IO.File]::OpenRead($plainZip)
try { $plainHash = $sha.ComputeHash($fsr) } finally { $fsr.Dispose(); $sha.Dispose() }

$iv = New-MaskBytes   # same helper: 16 random bytes

$aes = [Security.Cryptography.Aes]::Create()
$aes.KeySize = 256
$aes.Mode    = [Security.Cryptography.CipherMode]::CBC
$aes.Padding = [Security.Cryptography.PaddingMode]::PKCS7
$aes.Key     = $key
$aes.IV      = $iv

$in  = [IO.File]::OpenRead($plainZip)
$out = [IO.File]::Create($encFile)
try {
    $out.Write([Text.Encoding]::ASCII.GetBytes('DXPL'), 0, 4)
    $out.WriteByte(1)
    $out.Write($iv, 0, 16)
    $out.Write($plainHash, 0, 32)

    $encryptor = $aes.CreateEncryptor()
    $cs = New-Object Security.Cryptography.CryptoStream($out, $encryptor, [Security.Cryptography.CryptoStreamMode]::Write)
    try { $in.CopyTo($cs, 1048576) } finally { $cs.Dispose() }
} finally {
    $in.Dispose(); $out.Dispose(); $aes.Dispose()
}

$encMb = [math]::Round((Get-Item -LiteralPath $encFile).Length / 1MB, 1)
Ok "payload.enc = $encMb MB   (560 = 549 + 1 MB header/padding)"
Write-Host ("  plaintext sha256 : " + ([BitConverter]::ToString($plainHash).Replace('-','').ToLowerInvariant()))

# ------------------------------------------------------------------- 6. build it
Head 'Building one-file setup (dotnet publish - takes a few minutes)'

$publishDir = Join-Path $root 'launcher\publish'
if (Test-Path -LiteralPath $publishDir) { Remove-Item -LiteralPath $publishDir -Recurse -Force }

$csproj = Join-Path $root 'launcher\LaunchPanel.csproj'
& dotnet publish $csproj -c Release -r win-x64 -p:Version=$Version -o $publishDir
if ($LASTEXITCODE -ne 0) { Bad "dotnet publish failed (exit $LASTEXITCODE)"; exit 1 }

$setup = Join-Path $publishDir 'DeveloperXPanel-Setup.exe'
if (-not (Test-Path -LiteralPath $setup)) { Bad "Setup exe was not produced: $setup"; exit 1 }

$setupMb = [math]::Round((Get-Item -LiteralPath $setup).Length / 1MB, 1)

# ------------------------------------------------------- 7. file it in the tree
Head 'Filing the result'

$buildDir = Join-Path $root 'Build'
New-Item -ItemType Directory -Force -Path $buildDir | Out-Null
Copy-Item -LiteralPath $setup -Destination (Join-Path $buildDir 'DeveloperXPanel-Setup.exe') -Force
Ok 'Build\DeveloperXPanel-Setup.exe'

$versionDir = Join-Path (Join-Path $root 'Version') $tag
New-Item -ItemType Directory -Force -Path $versionDir | Out-Null
Copy-Item -LiteralPath $setup -Destination (Join-Path $versionDir 'DeveloperXPanel-Setup.exe') -Force
Ok "Version\$tag\DeveloperXPanel-Setup.exe"

if (-not $KeepPayload) {
    Remove-Item -LiteralPath $plainZip -Force -ErrorAction SilentlyContinue
    Remove-Item -LiteralPath $encFile  -Force -ErrorAction SilentlyContinue
    Ok 'payload.zip / payload.enc removed (pass -KeepPayload to keep them)'
}

Write-Host ""
Write-Host "  DONE" -ForegroundColor Green
Write-Host "  one file : DeveloperXPanel-Setup.exe   $setupMb MB   (AES-256 payload inside)" -ForegroundColor White
Write-Host "  customer : run it -> panel installs to %LOCALAPPDATA%\DeveloperXPanel and opens" -ForegroundColor Gray
Write-Host ""
